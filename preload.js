const {contextBridge,ipcRenderer,webUtils}=require('electron');
const call=(ch,...a)=>ipcRenderer.invoke(ch,...a);
contextBridge.exposeInMainWorld('desk',{
  openFiles:()=>call('dlg:files'),
  openSub:()=>call('dlg:sub'),
  pickFolder:()=>call('dlg:folder'),
  readText:p=>call('fs:text',p),
  siblings:p=>call('fs:siblings',p),
  folder:p=>call('fs:folder',p),
  saveShot:(data,dir,name)=>call('shot:save',data,dir,name),
  reveal:p=>call('shell:reveal',p),
  onTop:on=>call('win:top',on),
  setSize:(w,h,x)=>call('win:size',w,h,x),
  leaveFull:()=>call('win:leaveFull'),
  setMinWidth:w=>call('win:minw',w),
  setAspect:(r,x)=>call('win:aspect',r,x),
  keepAwake:on=>call('power',on),
  resolve:u=>call('net:resolve',u),
  saveRec:(buf,dir,name)=>call('rec:save',buf,dir,name),
  minimize:()=>call('win:min'),
  toggleMax:()=>call('win:max'),
  closeWin:()=>call('win:close'),
  winState:()=>call('win:state'),
  onWinState:cb=>ipcRenderer.on('win:changed',(_e,s)=>cb(s)),
  translate:(t,l)=>call('tr:go',t,l),
  dictLookup:(w,sl)=>call('dict:go',w,sl),
  subDbLoad:()=>call('subdb:load'),
  subDbSave:d=>call('subdb:save',d),
  subSearch:o=>call('subs:search',o),
  subFetch:(l,e)=>call('subs:fetch',l,e),
  subSave:(t,o)=>call('subs:save',t,o),
  subWrite:(t,o)=>call('subs:write',t,o),
  probe:p=>call('av:probe',p),
  subExtract:(p,i)=>call('av:sub',p,i),
  subLive:(p,i,ss)=>call('av:subLive',p,i,ss),
  subStop:id=>call('av:subStop',id),
  onSubChunk:cb=>ipcRenderer.on('sub:chunk',(_e,m)=>cb(m)),
  thumb:(p,t)=>call('av:thumb',p,t),
  audioUrl:(p,i,ss)=>call('av:audio',p,i,ss),
  thumbState:(p,h)=>call('thumb:state',p,h),
  thumbProgress:f=>call('thumb:progress',f),
  onThumb:cb=>ipcRenderer.on('thumb:cmd',(_e,c)=>cb(c)),
  appInfo:()=>call('app:info'),
  checkUpdate:()=>call('upd:check'),
  openDoc:n=>call('app:doc',n),
  docText:n=>call('app:docText',n),
  openUrl:u=>call('app:open',u),
  pathOf:f=>webUtils.getPathForFile(f),
  onOpen:cb=>ipcRenderer.on('open-files',(_e,files)=>cb(files))
});
